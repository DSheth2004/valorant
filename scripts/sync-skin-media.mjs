// Regenerates server/src/data/skinMedia.js: the in-game showcase videos (upgrade levels,
// VFX, finishers…) for every skin in the catalog, sourced from valorant-api.com.
// Video URLs include Riot's release version, so re-run this after a game patch if
// videos stop loading:  npm run sync:media
import { writeFile } from "node:fs/promises";
import { WEAPONS } from "../server/src/data/weapons.js";

const OUTPUT = new URL("../server/src/data/skinMedia.js", import.meta.url);

const LEVEL_LABELS = {
  VFX: "VFX",
  Animation: "Animation",
  Finisher: "Finisher",
  KillCounter: "Kill counter",
  SoundEffects: "Sound",
  TopFrag: "Top frag",
  KillBanner: "Kill banner",
  KillEffect: "Kill effect",
  Transformation: "Transformation",
  Randomizer: "Randomizer",
  InspectAndKill: "Inspect & kill",
  HeartbeatAndMapSensor: "Heartbeat sensor",
};

const humanize = (item) =>
  LEVEL_LABELS[item] ?? item.replace(/([a-z])([A-Z])/g, "$1 $2").replace(/^./, (c) => c.toUpperCase());

const response = await fetch("https://valorant-api.com/v1/weapons");
if (!response.ok) throw new Error(`valorant-api.com responded ${response.status}`);
const { data } = await response.json();
const apiWeapons = new Map(data.map((weapon) => [weapon.displayName.toLowerCase(), weapon]));

const media = {};
const missing = [];

for (const weapon of WEAPONS) {
  const apiWeapon = apiWeapons.get(weapon.id === "knife" ? "melee" : weapon.name.toLowerCase());
  const skinsByName = new Map(apiWeapon.skins.map((skin) => [skin.displayName.trim().toLowerCase(), skin]));

  for (const skin of weapon.skins) {
    const apiSkin = skinsByName.get(skin.name.toLowerCase());
    const videos = (apiSkin?.levels ?? [])
      .map((level, index) => {
        if (!level.streamedVideo) return null;
        const item = level.levelItem?.split("::").pop();
        const label = item && item !== "None" ? humanize(item) : index === 0 ? "Base" : `Level ${index + 1}`;
        return { level: index + 1, label, url: level.streamedVideo };
      })
      .filter(Boolean);

    if (videos.length) media[skin.id] = videos;
    else missing.push(skin.id);
  }
}

const header = `// Generated by scripts/sync-skin-media.mjs. Do not edit by hand.\n// Source: valorant-api.com. Videos are streamed from Riot's CDN.\n`;
await writeFile(OUTPUT, `${header}export const SKIN_MEDIA = ${JSON.stringify(media, null, 2)};\n`);

const total = Object.values(media).reduce((sum, videos) => sum + videos.length, 0);
console.log(`Wrote ${total} videos for ${Object.keys(media).length} skins.`);
if (missing.length) console.warn(`No videos found for: ${missing.join(", ")}`);
